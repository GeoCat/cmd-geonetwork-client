package com.geocat.gnclient.gnservices.metadata.model.v4;

public class StatusValue {
    private String type;
    private String name;

    public StatusValue() {
        // no-args constructor
    }

    public String getType() {
        return type;
    }

    public void setType(String type) {
        this.type = type;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
}
